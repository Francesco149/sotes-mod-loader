#!/usr/bin/env python3
"""itemsites.py — every place the code holds the address of the static item-definition table.

The item definitions are one static array in the exe's .data (item_table: enold 0x6c0cd0, 215 rows of 736 B; SE EN
0x6a6210 / JP 0x6a4210, 306 rows of 940 B), ended by a row whose id (+0) is 0.  Every lookup scans it inline from the
start until that 0 (SE then falls back to its generated-gear table, sys + 0x308: ids 910000 + slot) — there is no
count and no end pointer anywhere.  To give mods items of their own the loader RELOCATES the table: a copy with the
retail rows in front, the mods' rows after them, then the 0 row, and every reference rebased onto it
(core/lua/items.lua).

The census (all three editions) is total and uniform: every reference is the table BASE itself — `[T]` (the first
id), `[reg*4 + T]` / `[reg + T]` (a scan), or the imm32 T (`imul reg, rowsize` + `add reg, T`: the found row's
address).  No field offset is ever folded into a displacement (fields are read through the row pointer), so a
rebase is one dword per site.  Cross-check: the 4-byte value T occurs in the whole file exactly at these sites
(77 / 106 / 106) — no data pointer to the table exists, and no code outside IDA's functions.

Output: core/gen/sotes_itemsites.c — the VAs of those dword fields (numbers only, no game bytes).

  python3 tools/itemsites.py            # write core/gen/sotes_itemsites.c
  python3 tools/itemsites.py --print    # per-edition report, no write
"""
import argparse
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from symgen import EXES, PE  # noqa: E402
from banksites import funcs  # noqa: E402

import capstone  # noqa: E402
from capstone import x86  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "core", "gen", "sotes_itemsites.c")
EDS = ("enold", "ense-en", "ense-jp")
# table, row size, the icon bank (the stock list's icon cells: sys + 0xb74 enold / 0xbe8 EN / 0xbf4 JP), the pickup
# kind foe_drops spawns for an item (pickup_spawn's first arg)
LAYOUT = {
    "enold": (0x6c0cd0, 736, 50, 100162),
    "ense-en": (0x6a6210, 940, 56, 100168),
    "ense-jp": (0x6a4210, 940, 60, 100168),
}
MD = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
MD.detail = True


def scan(ed):
    pe = PE(EXES[ed])
    t, rs, _, _ = LAYOUT[ed]
    n = 0
    while struct.unpack("<I", pe.read(t + rs * n, 4))[0] != 0:
        n += 1
    sites, near = [], []
    pat = struct.pack("<I", t)
    for va, size, name in funcs(ed):
        code = pe.read(va, size)
        if not code:
            continue
        for ins in MD.disasm(code, va):
            hit = False
            for op in ins.operands:
                if op.type == x86.X86_OP_IMM and (op.imm & 0xFFFFFFFF) == t:
                    hit = True
                elif op.type == x86.X86_OP_MEM:
                    d = op.mem.disp & 0xFFFFFFFF
                    if d == t:
                        hit = True
                    elif t < d < t + rs * (n + 1):
                        near.append((ins.address, name, f"{ins.mnemonic} {ins.op_str}"))
            if hit:
                i = bytes(ins.bytes).find(pat)
                assert i >= 0, (ed, hex(ins.address))
                sites.append((ins.address + i, ins.address, name, f"{ins.mnemonic} {ins.op_str}"))
    # the whole file: T occurs nowhere else
    raw = []
    for sname, sva, vsz, rptr, rsz in pe.secs:
        d = pe.d[rptr:rptr + rsz]
        i = d.find(pat)
        while i >= 0:
            raw.append(sva + i)
            i = d.find(pat, i + 1)
    assert sorted(raw) == sorted(s[0] for s in sites), (ed, "the table address occurs outside the census")
    assert not near, (ed, "a displacement inside the table", near[:3])
    return n, sites


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--print", action="store_true")
    a = ap.parse_args()
    res = {ed: scan(ed) for ed in EDS}
    for ed in EDS:
        n, sites = res[ed]
        print(f"{ed}: {n} rows, {len(sites)} sites in {len({s[2] for s in sites})} functions")
        if a.print:
            for s in sites:
                print(f"   {s[1]:08x} {s[2]:40s} {s[3]}")
    if a.print:
        return
    out = ["// GENERATED by tools/itemsites.py — do not edit.  The dword fields that hold the static item table's address",
           "// (numbers only; no game bytes).",
           '#include "../sotes_itemsites.h"', ""]
    for ed in EDS:
        n, sites = res[ed]
        cn = ed.replace("-", "_")
        out.append(f"static const uint32_t sites_{cn}[] = {{")
        vas = sorted(s[0] for s in sites)
        for i in range(0, len(vas), 8):
            out.append("    " + ", ".join(f"0x{v:08x}u" for v in vas[i:i + 8]) + ",")
        out.append("};")
    out.append("")
    out.append("const ItemSites g_itemsites[3] = {")
    for ed in EDS:
        n, sites = res[ed]
        t, rs, bank, kind = LAYOUT[ed]
        cn = ed.replace("-", "_")
        out.append(f'    {{ "{ed}", 0x{t:08x}u, {rs}, {n}, {bank}, {kind}, {len(sites)}, sites_{cn} }},')
    out.append("};")
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
